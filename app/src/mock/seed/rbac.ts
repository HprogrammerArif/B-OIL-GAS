const SCOPE_RANK: Record<GrantScope, number> = { SELF: 0, TEAM: 1, DEPARTMENT: 2, SITE: 3, COMPANY: 4 };

/** Flattened grants for a set of roles; the widest scope wins per key (doc 03 §2.3). */
export function grantsForRoles(roles: RoleKey[]): PermissionGrant[] {
  const byKey = new Map<string, PermissionGrant>();
  const add = (spec: GrantSpec, via: string) => {
    const [key, scope, maxAmount] = spec;
    const existing = byKey.get(key);
    if (!existing || SCOPE_RANK[scope] > SCOPE_RANK[existing.scope]) {
      byKey.set(key, { key, scope, via, maxAmount: maxAmount ?? null });
    }
  };
  BASE.forEach((g) => add(g, "ROLE:EMPLOYEE"));
  roles.forEach((role) => (ROLE_GRANTS[role] ?? []).forEach((g) => add(g, `ROLE:${role}`)));
  return [...byKey.values()].sort((a, b) => a.key.localeCompare(b.key));
}

/**
 * Module → grants that reveal it in the shell. A module appears when any listed key is held;
 * `readAbove` also reveals it for a read key held above SELF, so personal records alone do not surface a desk.
 */
const NAV_RULES: { module: ModuleKey; anyOf: PermissionKey[]; readAbove?: PermissionKey }[] = [
  { module: "dashboards", anyOf: ["dashboards:read"] },
  { module: "approvals", anyOf: ["workflow:inbox"] },
  { module: "notices", anyOf: ["notices:read"] },
  { module: "note-sheets", anyOf: ["note-sheets:read"] },
  { module: "attendance", anyOf: ["attendance:punch"] },
  { module: "leave", anyOf: ["leave:request"] },
  { module: "claims", anyOf: ["claims:create"] },
  { module: "fleet", anyOf: ["fleet:request", "fleet:drive", "fleet:dispatch"] },
  { module: "bus", anyOf: ["bus:seat-self", "bus:manage"] },
  { module: "parcels", anyOf: ["parcels:read"] },
  { module: "visitors", anyOf: ["visitors:create", "visitors:gate"], readAbove: "visitors:read" },
  { module: "incidents", anyOf: ["incidents:report"] },
  { module: "assets", anyOf: ["assets:read"] },
  { module: "compliance", anyOf: ["compliance:read"] },
  { module: "employees", anyOf: ["employees:read"] },
  { module: "chat", anyOf: ["chat:use"] },
];

export function navigationFor(grants: PermissionGrant[]): ModuleKey[] {
  const held = new Map(grants.map((g) => [g.key, g.scope]));
  return NAV_RULES.filter(({ anyOf, readAbove }) => {
    if (anyOf.some((k) => held.has(k))) return true;
    const scope = readAbove ? held.get(readAbove) : undefined;
    return scope !== undefined && scope !== "SELF";
  }).map((r) => r.module);
}

